"""Writes the flour table the engine compiles in, from the sourced model.

    py research/tools/export_flour_table.py            # writes crates/breadator-engine/src/flour/data.rs
    py research/tools/export_flour_table.py --check    # fails if that file is out of date

`research/data/model-flour.json` holds every value with its sources, evidence label and
reasoning; the flour calculator needs only the numbers. This script copies them into Rust
constants, and fails loudly if the model stops having a value the calculator relies on.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
MODEL = ROOT / "research" / "data" / "model-flour.json"
OUT = ROOT / "crates" / "breadator-engine" / "src" / "flour" / "data.rs"

# Model group -> what the engine distinguishes.
GROUPS = {
    "wheat-white": "Wheat",
    "wheat-high-extraction": "Wheat",
    "wheat-wholemeal": "Wheat",
    "rye": "Rye",
    "ancient-wheat": "Ancient",
    "durum": "Durum",
    "gluten-free": "Other",
    "gluten-free (if certified)": "Other",
    "non-wheat (contains gluten proteins)": "Other",
}
AMYLASE = {"normal": "Normal", "high": "High", "low": "Low", "very low": "VeryLow", "unknown": "Unknown"}
# Scald methods of `scalds.water_shift.k_by_method`, recognised by a phrase of their description.
SCALDS = {"yudane": "Yudane", "held at 60-70": "Hot", "cooked": "Cooked"}


def num(x: float) -> str:
    """A Rust f64 literal."""
    return repr(float(x))


def band(value: dict | None) -> str:
    """`Some(Band)` of a model value, or `None` when the model has no number."""
    if not value or value.get("typical") is None or not value.get("range"):
        return "None"
    low, high = value["range"]
    return f"Some(Band {{ low: {num(low)}, mid: {num(value['typical'])}, high: {num(high)} }})"


def export() -> str:
    model = json.loads(MODEL.read_text(encoding="utf-8"))
    out = [
        "// Generated by research/tools/export_flour_table.py from research/data/model-flour.json,",
        "// where every number has its sources and evidence label. Do not edit: run the script.",
        "",
        "use super::{AdditionWater, Amylase, Band, FlourType, Group, ScaldKind, ScaldWater};",
        "",
        f"pub(super) const GLUTEN_PROTEIN_PCT: f64 = {num(model['vital_gluten']['composition']['protein_pct_as_is']['typical'])};",
        "",
        "pub(super) const TYPES: &[FlourType] = &[",
    ]
    for t in model["flours"]["types"]:
        protein = band(t["protein_pct"])
        if protein == "None":
            raise SystemExit(f"{t['id']}: no protein value")
        retard = t["cold_retard"].get("max_h")
        out.append(
            f'    FlourType {{ id: "{t["id"]}", group: Group::{GROUPS[t["group"]]}, '
            f"protein: {protein[5:-1]}, fibre_pct: {num(t['fibre_pct']['typical'])}, "
            f"absorption: {band(t.get('water_absorption_pct'))}, "
            f"hydration: {band(t.get('bread_hydration_pct'))}, "
            f"network: {str(bool(t['gluten']['network'])).lower()}, "
            f"retard_h: {'None' if retard is None else f'Some({num(retard)})'}, "
            f"amylase: Amylase::{AMYLASE[t['enzyme_activity']['class']]} }},"
        )
    out += ["];", "", "pub(super) const ADDITIONS: &[AdditionWater] = &["]
    for a in model["hydration_method"]["addition_coefficients"]:
        if a.get("k_g_water_per_g") is None:
            continue
        low, high = a["k_range"]
        out.append(
            f'    AdditionWater {{ kind: "{a["kind"]}", k: {num(a["k_g_water_per_g"])}, '
            f"k_low: {num(low)}, k_high: {num(high)} }},"
        )
    out += ["];", "", "pub(super) const SCALDS: &[ScaldWater] = &["]
    for phrase, name in SCALDS.items():
        found = [m for m in model["scalds"]["water_shift"]["k_by_method"] if phrase in m["method"]]
        if len(found) != 1:
            raise SystemExit(f"scald method '{phrase}': {len(found)} matches in the model")
        low, high = found[0]["range"]
        out.append(
            f"    ScaldWater {{ kind: ScaldKind::{name}, k: {num(found[0]['k'])}, "
            f"k_low: {num(low)}, k_high: {num(high)} }},"
        )
    out += ["];", ""]
    return "\n".join(out)


def main() -> int:
    text = export()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"out of date: {OUT.relative_to(ROOT)} (run export_flour_table.py)", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)}: {text.count('FlourType {')} flour types")
    return 0


if __name__ == "__main__":
    sys.exit(main())
